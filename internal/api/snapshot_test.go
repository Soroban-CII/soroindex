// update regenerates testdata/snapshots and the generated section of
// docs/api.md: go test ./internal/api -run Snapshot -update
var update = flag.Bool("update", false, "rewrite golden API snapshots and the docs/api.md fixture section")

const (
	snapshotDir  = "testdata/snapshots"
	apiDocPath   = "../../docs/api.md"
	docsBegin    = "<!-- BEGIN fixture snapshots: generated by `go test ./internal/api -run Snapshot -update`; do not edit by hand -->"
	docsEnd      = "<!-- END fixture snapshots -->"
	fixtureFirst = uint32(5062907) // first recorded testnet ledger
	fixtureLast  = uint32(5062910)
	fixtureTip   = uint32(5062915)
)

// noCodeRPC is the node for the fixture: it has no entries, so code that
// only the recorded ledgers reference is stored as archived and a reference
// that no ledger defined stays unresolved. Nothing else is called.
type noCodeRPC struct{}

func (noCodeRPC) GetNetwork(context.Context) (rpc.Network, error) {
	return rpc.Network{}, errors.New("not used")
}
func (noCodeRPC) GetLatestLedger(context.Context) (rpc.LatestLedger, error) {
	return rpc.LatestLedger{Sequence: fixtureTip}, nil
}
func (noCodeRPC) GetLedgers(context.Context, rpc.LedgersRequest) (rpc.LedgersPage, error) {
	return rpc.LedgersPage{}, errors.New("not used")
}
func (noCodeRPC) GetLedgerEntries(context.Context, []string) (rpc.LedgerEntries, error) {
	return rpc.LedgerEntries{LatestLedger: fixtureTip}, nil
}

// snapshotFixture names the contracts the snapshots read.
type snapshotFixture struct {
	server                                        *Server
	token, legacy, falseClaim, multi, upgraded    string
	sac, reference, unresolved, owner, unknown    string
	fullHash, partialHash, notTokenHash, recorded string
	referenceTag, unresolvedTag                   string
}

func fixtureContract(t *testing.T, n byte) string {
	t.Helper()
	var b [32]byte
	b[0], b[31] = 0xf0, n
	id, err := strkey.Encode(strkey.VersionByteContract, b[:])
	if err != nil {
		t.Fatal(err)
	}
	return id
}

func scContract(t *testing.T, id string) xdr.ScAddress {
	t.Helper()
	raw, err := strkey.Decode(strkey.VersionByteContract, id)
	if err != nil {
		t.Fatal(err)
	}
	var cid xdr.ContractId
	copy(cid[:], raw)
	return xdr.ScAddress{Type: xdr.ScAddressTypeScAddressTypeContract, ContractId: &cid}
}

func dataEntry(cd xdr.ContractDataEntry) *xdr.LedgerEntry {
	return &xdr.LedgerEntry{Data: xdr.LedgerEntryData{Type: xdr.LedgerEntryTypeContractData, ContractData: &cd}}
}

func instance(t *testing.T, id string, ex xdr.ContractExecutable, kind ingest.ChangeKind) ingest.Change {
	t.Helper()
	return ingest.Change{Kind: kind, Entry: dataEntry(xdr.ContractDataEntry{
		Contract: scContract(t, id), Durability: xdr.ContractDataDurabilityPersistent,
		Key: xdr.ScVal{Type: xdr.ScValTypeScvLedgerKeyContractInstance},
		Val: xdr.ScVal{Type: xdr.ScValTypeScvContractInstance, Instance: &xdr.ScContractInstance{Executable: ex}},
	})}
}

func wasmExec(t *testing.T, hash string) xdr.ContractExecutable {
	t.Helper()
	h, err := ingest.ParseWasmHash(hash)
	if err != nil {
		t.Fatal(err)
	}
	return xdr.ContractExecutable{Type: xdr.ContractExecutableTypeContractExecutableWasm, WasmHash: &h}
}

func refExec(t *testing.T, owner, tag string) xdr.ContractExecutable {
	t.Helper()
	return xdr.ContractExecutable{Type: xdr.ContractExecutableTypeContractExecutableExternalRef,
		ExternalRef: &xdr.ContractExecutableExternalRef{ExecutableOwner: scContract(t, owner), Tag: xdr.ScString(tag)}}
}

func execTag(t *testing.T, owner, tag, hash string) ingest.Change {
	t.Helper()
	h, err := ingest.ParseWasmHash(hash)
	if err != nil {
		t.Fatal(err)
	}
	b := xdr.ScBytes(h[:])
	s := xdr.ScString(tag)
	return ingest.Change{Kind: ingest.Created, Entry: dataEntry(xdr.ContractDataEntry{Contract: scContract(t, owner), Durability: xdr.ContractDataDurabilityPersistent,
		Key: xdr.ScVal{Type: xdr.ScValTypeScvExecutableTag, ExecutableTag: &s}, Val: xdr.ScVal{Type: xdr.ScValTypeScvBytes, Bytes: &b}})}
}

func goldenCode(t *testing.T, name string) (ingest.Change, string) {
	t.Helper()
	code, err := os.ReadFile(filepath.Join("../../testdata/wasm", name)) // #nosec G304 -- fixed fixture names
	if err != nil {
		t.Fatal(err)
	}
	sum := sha256.Sum256(code)
	entry := xdr.LedgerEntry{Data: xdr.LedgerEntryData{Type: xdr.LedgerEntryTypeContractCode, ContractCode: &xdr.ContractCodeEntry{Hash: xdr.Hash(sum), Code: code}}}
	return ingest.Change{Kind: ingest.Created, Entry: &entry}, hex.EncodeToString(sum[:])
}

// recordedFacts decodes the real testnet ledgers recorded for the rpc
// package (internal/rpc/testdata/README.md).
func recordedFacts(t *testing.T) []ingest.ContractFacts {
	t.Helper()
	b, err := os.ReadFile("../rpc/testdata/getLedgers.json")
	if err != nil {
		t.Fatal(err)
	}
	var resp struct {
		Result struct {
			Ledgers []struct {
				MetadataXDR string `json:"metadataXdr"`
			} `json:"ledgers"`
		} `json:"result"`
	}
	if err := json.Unmarshal(b, &resp); err != nil {
		t.Fatal(err)
	}
	var out []ingest.ContractFacts
	for _, l := range resp.Result.Ledgers {
		var m xdr.LedgerCloseMeta
		if err := ingest.UnmarshalBase64(l.MetadataXDR, &m, ingest.XDRLimits{MaxBase64Len: 8 << 20}); err != nil {
			t.Fatal(err)
		}
		f, err := ingest.ExtractContractFacts(m)
		if err != nil {
			t.Fatal(err)
		}
		out = append(out, f)
	}
	if len(out) != 2 || out[0].Ledger != fixtureFirst {
		t.Fatalf("recorded ledgers changed: %d", len(out))
	}
	return out
}

// buildSnapshotFixture indexes the recorded testnet ledgers and then two
// synthetic ledgers carrying the golden Wasm through the real ingest path:
// a declared token, an undeclared full token, a false claim, a multi-SEP
// declaration, a SAC, a CAP-85 reference contract, an unresolved reference,
// and a contract upgraded from the full token to the partial one.
func buildSnapshotFixture(t *testing.T) snapshotFixture {
	t.Helper()
	ctx := context.Background()
	f := snapshotFixture{
		token: fixtureContract(t, 1), legacy: fixtureContract(t, 2), falseClaim: fixtureContract(t, 3), multi: fixtureContract(t, 4),
		upgraded: fixtureContract(t, 5), sac: fixtureContract(t, 6), reference: fixtureContract(t, 7), unresolved: fixtureContract(t, 8),
		owner: fixtureContract(t, 9), unknown: fixtureContract(t, 99), referenceTag: "token-v1", unresolvedTag: "never-defined",
	}
	path := filepath.Join(t.TempDir(), "snapshot.db")
	w, err := store.Open(ctx, path, store.Options{Passphrase: "Test SDF Network ; September 2015"})
	if err != nil {
		t.Fatal(err)
	}
	rf, err := match.LoadRules(rules.FS)
	if err != nil {
		t.Fatal(err)
	}
	ix := &ingest.Indexer{Store: w, RPC: noCodeRPC{}, Rules: rf, Limits: sepmeta.DefaultLimits(), Claims: claims.Default(sepmeta.DefaultLimits()),
		Log: slog.New(slog.NewTextHandler(io.Discard, nil)), Now: func() time.Time { return time.Date(2026, 11, 21, 0, 0, 0, 0, time.UTC) }}

	facts := recordedFacts(t)
	if len(facts[1].CodeCreated) != 1 {
		t.Fatalf("recorded ledger %d no longer creates one code entry", facts[1].Ledger)
	}
	f.recorded = facts[1].CodeCreated[0]

	full, fullHash := goldenCode(t, "token_full_sep.wasm")
	legacy, legacyHash := goldenCode(t, "token_full_legacy.wasm")
	partial, partialHash := goldenCode(t, "token_partial.wasm")
	notToken, notTokenHash := goldenCode(t, "not_token.wasm")
	multi, multiHash := goldenCode(t, "multi_sep.wasm")
	noMeta, _ := goldenCode(t, "no_meta.wasm")
	f.fullHash, f.partialHash, f.notTokenHash = fullHash, partialHash, notTokenHash
	facts = append(facts, ingest.ContractFacts{Ledger: fixtureFirst + 2, Changes: []ingest.Change{
		full, legacy, partial, notToken, multi, noMeta,
		instance(t, f.token, wasmExec(t, fullHash), ingest.Created),
		instance(t, f.legacy, wasmExec(t, legacyHash), ingest.Created),
		instance(t, f.falseClaim, wasmExec(t, notTokenHash), ingest.Created),
		instance(t, f.multi, wasmExec(t, multiHash), ingest.Created),
		instance(t, f.upgraded, wasmExec(t, fullHash), ingest.Created),
		instance(t, f.sac, xdr.ContractExecutable{Type: xdr.ContractExecutableTypeContractExecutableStellarAsset}, ingest.Created),
		execTag(t, f.owner, f.referenceTag, fullHash),
		instance(t, f.reference, refExec(t, f.owner, f.referenceTag), ingest.Created),
		instance(t, f.unresolved, refExec(t, f.owner, f.unresolvedTag), ingest.Created),
	}}, ingest.ContractFacts{Ledger: fixtureLast, Changes: []ingest.Change{
		instance(t, f.upgraded, wasmExec(t, partialHash), ingest.Updated),
	}})
	tx, err := w.Begin(ctx)
	if err != nil {
		t.Fatal(err)
	}
	for _, lf := range facts {
		if err := ix.ApplyLedger(ctx, tx, lf); err != nil {
			t.Fatalf("ledger %d: %v", lf.Ledger, err)
		}
	}
	if err := tx.SetLastLedger(ctx, fixtureLast); err != nil {
		t.Fatal(err)
	}
	if err := tx.Commit(); err != nil {
		t.Fatal(err)
	}
	// Verified tier: a current pass for the declared token and a pass on the
	// upgraded contract's old code, which must show as stale.
	for _, v := range []struct{ id, hash string }{{f.token, fullHash}, {f.upgraded, fullHash}} {
		if _, err := w.DB.ExecContext(ctx, `INSERT INTO verifications (contract_id,wasm_hash,sep,tool,tool_version,verdict,passed,clauses_json,run_at) VALUES (?,?,41,'soroban-guard','0.0.0-fixture','pass',1,'[]','2026-11-21T00:00:00Z')`, v.id, v.hash); err != nil {
			t.Fatal(err)
		}
	}
	if err := w.Close(); err != nil {
		t.Fatal(err)
	}
	ro, err := store.Open(ctx, path, store.Options{Passphrase: "Test SDF Network ; September 2015", ReadOnly: true})
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = ro.Close() })
	f.server, err = New(Options{Store: ro, Network: "testnet", RPC: tip{sequence: fixtureTip}})
	if err != nil {
		t.Fatal(err)
	}
	return f
}

